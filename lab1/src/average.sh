#!/usr/bin/env bash

# Проверка: есть ли аргументы
if [ $# -eq 0 ]; then
    echo "Ошибка: не переданы входные аргументы." >&2
    echo "Использование: ./average.sh число1 число2 ..." >&2
    exit 1
fi

# Передаем все аргументы ($@) в awk.
# $@ распаковывается в список слов, awk воспринимает их как записи (по одной на строку),
# либо мы можем явно сказать awk обработать их как поля.
# Самый простой и надежный вариант: превратить аргументы в поток строк для awk.

# Вариант А: Используем printf, чтобы вывести каждый аргумент на новой строке,
# и передаем этот поток в awk. Это работает даже если числа очень длинные.
printf '%s\n' "$@" | awk '
{
    # $1 содержит текущее число из потока
    sum += $1
    count++
}
END {
    if (count > 0) {
        # %.2f форматирует вывод до 2 знаков после запятой
        printf "Количество чисел: %d\n", count
        printf "Среднее арифметическое: %.2f\n", sum / count
    } else {
        print "Нет данных для расчета."
    }
}'
